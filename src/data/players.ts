export interface BuildPlayersOptions {
  seasonYear?: string;
  startingMarqueePlayerIds?: string[];
  marqueeMarkupPercent?: number;
}

export function getMarqueeCandidatesForLeague(
  leagueId: LeagueId,
  seasonYear?: string,
  teamPurse = 200 * CRORE,
  minBidFloor = 10 * LAKH,
  marqueeMarkupPercent = 15
): AuctionPlayer[] {
  const pool = buildPlayersForLeague(leagueId, 5, 18, teamPurse, minBidFloor, {
    seasonYear,
    marqueeMarkupPercent,
  });
  return pool.filter((p) => p.category === 'Marquee').slice(0, 18);
}

export function buildPlayersForLeague(
  leagueId: LeagueId,
  teamsCount = 5,
  maxSquadSize = 18,
  teamPurse = 200 * CRORE,
  minBidFloor = 10 * LAKH,
  options?: BuildPlayersOptions
): AuctionPlayer[] {
  const isFootball = FOOTBALL_LEAGUES.includes(leagueId);
  const isWpl = leagueId === 'WPL';
  const safeTeams = Math.max(2, teamsCount);
  const safeMaxSquad = Math.max(5, Math.min(25, maxSquadSize));
  const targetCount = safeTeams * safeMaxSquad + safeMaxSquad;
  const seasonYear = options?.seasonYear;
  const startingIds = new Set(options?.startingMarqueePlayerIds || []);
  const markupPercent = options?.marqueeMarkupPercent ?? 15;

  // 1. Start with curated league-matching real stars (keep WPL female stars strictly separate from men's pools)
  const primaryMatches = MASTER_PLAYERS.filter((p) => p.leagueTags.includes(leagueId));
  const secondaryMatches = isWpl
    ? []
    : MASTER_PLAYERS.filter(
        (p) =>
          (isFootball ? p.sport === 'football' : p.sport !== 'football' && !p.leagueTags.includes('WPL')) &&
          !primaryMatches.some((m) => m.id === p.id)
      );

  const curatedPool = [...primaryMatches, ...secondaryMatches].sort((a, b) => {
    if (seasonYear) {
      const aMatch = a.seasonsActive.includes(seasonYear) ? 1 : 0;
      const bMatch = b.seasonsActive.includes(seasonYear) ? 1 : 0;
      if (aMatch !== bMatch) return bMatch - aMatch;
    }
    if (leagueId === 'CUSTOM') {
      if (a.id === 'p-yuvraj') return -1;
      if (b.id === 'p-yuvraj') return 1;
    }
    return b.rating - a.rating;
  });

  const result: AuctionPlayer[] = curatedPool.slice(0, targetCount).map((p) => ({
    ...p,
    basePrice: computeScaledBasePrice(p.basePrice, teamPurse, minBidFloor),
    fantasyPoints: 0,
    status: 'upcoming',
  }));

  const usedNames = new Set(result.map((p) => p.name.toLowerCase()));

  // 2. Top up from deep real-player catalog before synthetic fallback
  const realExtraList = isFootball ? REAL_FOOTBALL_POOL : isWpl ? REAL_WPL_POOL : REAL_CRICKET_POOL;
  for (let i = 0; i < realExtraList.length && result.length < targetCount; i++) {
    const rp = realExtraList[i] as {
      name: string;
      country: string;
      overseas: boolean;
      role: PlayerRole;
      baseLakhs: number;
      rating: number;
      teamCode?: string;
      category?: 'Marquee';
    };
    if (usedNames.has(rp.name.toLowerCase())) continue;
    usedNames.add(rp.name.toLowerCase());
    const rawBase = rp.baseLakhs * LAKH;
    const role: PlayerRole = rp.role;
    const category = rp.category
      ? rp.category
      : isFootball
        ? role === 'Forward'
          ? 'Attacker'
          : role === 'Midfielder'
            ? 'Midfield Engine'
            : 'Defender / GK'
        : rp.baseLakhs <= 30
          ? 'Uncapped'
          : role === 'Batter'
            ? 'Capped Batter'
            : role === 'Bowler'
              ? 'Capped Bowler'
              : role === 'All-Rounder'
                ? 'Capped All-Rounder'
                : 'Wicketkeeper';

    result.push({
      id: `real-${leagueId.toLowerCase()}-${i + 1}`,
      name: rp.name,
      country: rp.country,
      isOverseas: rp.overseas,
      sport: isFootball ? 'football' : 'cricket',
      role,
      category,
      realTeamCode: rp.teamCode,
      leagueTags: [leagueId],
      seasonsActive: seasonYear ? [seasonYear, '2024', '2025'] : ['2024', '2025'],
      basePrice: computeScaledBasePrice(rawBase, teamPurse, minBidFloor),
      battingStyle: i % 3 === 0 ? (isFootball ? 'Left Foot' : 'Left-Hand Bat') : isFootball ? 'Right Foot' : 'Right-Hand Bat',
      bowlingStyle: isFootball
        ? role
        : role === 'Bowler'
          ? i % 2 === 0
            ? 'Right-Arm Fast'
            : 'Legbreak Spin'
          : role === 'All-Rounder'
            ? 'Right-Arm Medium'
            : 'None',
      rating: rp.rating,
      fantasyPoints: 0,
      stats: isFootball
        ? {
            matches: 75 + (i % 140),
            runs: role === 'Forward' ? 32 + (i % 65) : role === 'Midfielder' ? 14 + (i % 28) : 3 + (i % 9),
            average: 10 + (i % 32),
            strikeRate: Math.min(96, rp.rating),
            highestScore: '3G',
            fiftiesHundreds: '12 / 2',
            wickets: role === 'Defender' || role === 'Goalkeeper' ? 36 + (i % 55) : 0,
            economy: 0.85,
            bestBowling: role === 'Defender' || role === 'Goalkeeper' ? `${36 + (i % 55)} CS` : '-',
          }
        : {
            matches: 44 + (i % 110),
            runs: role === 'Batter' || role === 'Wicketkeeper' ? 1250 + (i % 2400) : role === 'All-Rounder' ? 680 + (i % 1200) : 90 + (i % 220),
            average: role === 'Bowler' ? 13.8 : 28.4 + (i % 16),
            strikeRate: role === 'Bowler' ? 116 : 136 + (i % 36),
            highestScore: role === 'Bowler' ? '28*' : `${74 + (i % 42)}*`,
            fiftiesHundreds: role === 'Bowler' ? '0 / 0' : `${6 + (i % 14)} / ${i % 4 === 0 ? 1 : 0}`,
            wickets: role === 'Bowler' ? 42 + (i % 95) : role === 'All-Rounder' ? 24 + (i % 48) : 0,
            economy: role === 'Bowler' || role === 'All-Rounder' ? Number((7.2 + (i % 19) * 0.1).toFixed(2)) : 0,
            bestBowling: role === 'Bowler' || role === 'All-Rounder' ? `${3 + (i % 3)}/${17 + (i % 15)}` : '-',
          },
      status: 'upcoming',
    });
  }

  // Maintain balanced role distribution across any remaining slots beyond real catalog
  const roleScheduleCricket = [
    'Batter', 'Bowler', 'Batter', 'Bowler', 'All-Rounder',
    'Batter', 'Bowler', 'All-Rounder', 'Wicketkeeper', 'Batter', 'Bowler',
  ] as const;
  const roleScheduleFootball = [
    'Forward', 'Midfielder', 'Defender', 'Forward', 'Midfielder',
    'Defender', 'Goalkeeper', 'Forward', 'Midfielder', 'Defender', 'Midfielder',
  ] as const;

  let idx = 0;
  while (result.length < targetCount) {
    const num = idx + 1;
    let candidateName = '';
    for (let attempt = 0; attempt < 25; attempt++) {
      const fList = isFootball ? FOOTBALL_FIRST_NAMES : CRICKET_FIRST_NAMES;
      const lList = isFootball ? FOOTBALL_LAST_NAMES : CRICKET_LAST_NAMES;
      const f = fList[(idx * 7 + attempt * 3) % fList.length];
      const l = lList[(idx * 11 + attempt * 5 + Math.floor(idx / 13)) % lList.length];
      const trial = attempt > 12 ? `${f} ${l} ${num}` : `${f} ${l}`;
      if (!usedNames.has(trial.toLowerCase())) {
        candidateName = trial;
        break;
      }
    }
    if (!candidateName) {
      candidateName = `${isFootball ? 'Club' : 'Squad'} Pro ${num}`;
    }
    usedNames.add(candidateName.toLowerCase());

    const countryMeta = isFootball
      ? FOOTBALL_COUNTRIES[idx % FOOTBALL_COUNTRIES.length]
      : CRICKET_COUNTRIES[idx % CRICKET_COUNTRIES.length];

    const role = isFootball
      ? roleScheduleFootball[idx % roleScheduleFootball.length]
      : roleScheduleCricket[idx % roleScheduleCricket.length];

    const baseTiers = [20 * LAKH, 30 * LAKH, 50 * LAKH, 75 * LAKH, 1 * CRORE, 1.5 * CRORE];
    const rawBasePrice = baseTiers[idx % baseTiers.length];
    const basePrice = computeScaledBasePrice(rawBasePrice, teamPurse, minBidFloor);
    const rating = 74 + ((idx * 7) % 16);

    const category = isFootball
      ? role === 'Forward'
        ? 'Attacker'
        : role === 'Midfielder'
          ? 'Midfield Engine'
          : 'Defender / GK'
      : rawBasePrice <= 30 * LAKH
        ? 'Uncapped'
        : role === 'Batter'
          ? 'Capped Batter'
          : role === 'Bowler'
            ? 'Capped Bowler'
            : role === 'All-Rounder'
              ? 'Capped All-Rounder'
              : 'Wicketkeeper';

    result.push({
      id: `gen-${leagueId.toLowerCase()}-${num}`,
      name: candidateName,
      country: countryMeta.name,
      isOverseas: countryMeta.overseas,
      sport: isFootball ? 'football' : 'cricket',
      role,
      category,
      leagueTags: [leagueId],
      seasonsActive: seasonYear ? [seasonYear] : ['2025'],
      basePrice,
      battingStyle: idx % 3 === 0 ? (isFootball ? 'Left Foot' : 'Left-Hand Bat') : isFootball ? 'Right Foot' : 'Right-Hand Bat',
      bowlingStyle: isFootball
        ? role
        : role === 'Bowler'
          ? idx % 2 === 0
            ? 'Right-Arm Fast'
            : 'Legbreak Spin'
          : role === 'All-Rounder'
            ? 'Right-Arm Medium'
            : 'None',
      rating,
      fantasyPoints: 0,
      stats: isFootball
        ? {
            matches: 40 + (idx % 120),
            runs: role === 'Forward' ? 18 + (idx % 45) : role === 'Midfielder' ? 8 + (idx % 20) : 2 + (idx % 8),
            average: 6 + (idx % 25),
            strikeRate: 78 + (idx % 14),
            highestScore: '2G',
            fiftiesHundreds: '4 / 0',
            wickets: role === 'Defender' || role === 'Goalkeeper' ? 18 + (idx % 40) : 0,
            economy: 0.9,
            bestBowling: '-',
          }
        : {
            matches: 22 + (idx % 85),
            runs: role === 'Batter' || role === 'Wicketkeeper' ? 620 + (idx % 1800) : role === 'All-Rounder' ? 380 + (idx % 900) : 45 + (idx % 150),
            average: role === 'Bowler' ? 12.4 : 26.5 + (idx % 15),
            strikeRate: role === 'Bowler' ? 112 : 132 + (idx % 34),
            highestScore: role === 'Bowler' ? '24*' : `${62 + (idx % 45)}*`,
            fiftiesHundreds: role === 'Bowler' ? '0 / 0' : `${3 + (idx % 12)} / ${idx % 5 === 0 ? 1 : 0}`,
            wickets: role === 'Bowler' ? 28 + (idx % 75) : role === 'All-Rounder' ? 16 + (idx % 42) : 0,
            economy: role === 'Bowler' || role === 'All-Rounder' ? Number((7.1 + (idx % 22) * 0.1).toFixed(2)) : 0,
            bestBowling: role === 'Bowler' || role === 'All-Rounder' ? `${3 + (idx % 2)}/${18 + (idx % 14)}` : '-',
          },
      status: 'upcoming',
    });
    idx += 1;
  }

  // 3. Apply Marquee pricing = Highest Price of that Team's Non-Marquee Player + 15%,
  // and place Selected Starting Marquee players right at the start of the auction (Lots #1..#K)
  const trimmed = result.slice(0, targetCount);
  const nonMarqueePlayers = trimmed.filter((p) => p.category !== 'Marquee' && !startingIds.has(p.id));
  const highestGlobalRegular = nonMarqueePlayers.reduce((max, p) => Math.max(max, p.basePrice), minBidFloor);
  const highestByTeam = new Map<string, number>();
  for (const p of nonMarqueePlayers) {
    if (p.realTeamCode) {
      highestByTeam.set(p.realTeamCode, Math.max(highestByTeam.get(p.realTeamCode) || 0, p.basePrice));
    }
  }

  const priced = trimmed.map((p) => {
    const isStartingSelected = startingIds.has(p.id);
    const isMarquee = p.category === 'Marquee' || isStartingSelected;
    if (!isMarquee) return p;

    const teamHighest = p.realTeamCode ? highestByTeam.get(p.realTeamCode) || highestGlobalRegular : highestGlobalRegular;
    const marqueePrice = computeMarqueePrice(
      Math.max(teamHighest, highestGlobalRegular),
      p.basePrice,
      teamPurse,
      minBidFloor,
      markupPercent
    );
    return {
      ...p,
      category: 'Marquee' as const,
      basePrice: marqueePrice,
    };
  });

  // Order Starting Marquee lots first at Lot #1..#K
  const ordered = priced.sort((a, b) => {
    const aSelected = startingIds.has(a.id) ? 1 : 0;
    const bSelected = startingIds.has(b.id) ? 1 : 0;
    if (aSelected !== bSelected) return bSelected - aSelected;

    if (leagueId === 'CUSTOM' && startingIds.size === 0) {
      if (a.id === 'p-yuvraj') return -1;
      if (b.id === 'p-yuvraj') return 1;
    }

    const aMarquee = a.category === 'Marquee' ? 1 : 0;
    const bMarquee = b.category === 'Marquee' ? 1 : 0;
    if (aMarquee !== bMarquee) return bMarquee - aMarquee;

    return 0;
  });

  return ordered;
}

